// Escape untrusted text before it goes into an HTML string (Leaflet popups,
// tooltips and divIcons render their content as innerHTML).
export function esc(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
